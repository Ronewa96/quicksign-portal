import React, { useEffect, useState } from 'react';
import { useDocuments } from '../../context/DocumentContext';
import { textToPdfBlob, downloadBlob, safeFileName } from '../../lib/textPdf';
import { AuditEvent } from '../../types';
import { LocationRecord, formatLocation } from '../../lib/location';
import { LocationText } from '../common/LocationText';
import {
  ShieldCheck,
  Search,
  Download,
  CheckCircle2,
  Lock,
  ExternalLink,
  Clock,
  UserCheck,
  HardDrive,
  FileCheck2,
  Copy,
  Check,
} from 'lucide-react';

/** One document's record: either sent for signing (on the server) or signed by the user on this device. */
interface AuditRecord {
  id: string;
  title: string;
  createdAt: string;
  pages: string[];
  status: string;
  transactionId?: string;
  certificateId?: string;
  sha256Hash?: string;
  signedAt?: string;
  signers: Array<{
    name: string;
    email: string;
    role: string;
    status: string;
    signedAt?: string;
    viewLocation?: LocationRecord;
    signLocation?: LocationRecord;
  }>;
  auditTrail: AuditEvent[];
}

export const AuditTrace: React.FC = () => {
  const { documents, activeDocumentId, setActiveDocumentId } = useDocuments();
  const [sent, setSent] = useState<AuditRecord[]>([]);
  const [selectedDocId, setSelectedDocId] = useState<string | undefined>(activeDocumentId || undefined);
  const [searchTx, setSearchTx] = useState('');
  const [hasCopiedHash, setHasCopiedHash] = useState(false);

  useEffect(() => {
    fetch('/api/requests')
      .then((res) => (res.ok ? res.json() : { requests: [] }))
      .then((data) => setSent((data.requests || []).map((r: any) => ({ ...r, signedAt: r.completedAt, certificateId: r.transactionId }))))
      .catch(() => setSent([]));
  }, []);

  const records: AuditRecord[] = [...sent, ...documents];
  const query = searchTx.trim().toLowerCase();
  const visible = query
    ? records.filter((r) => r.title.toLowerCase().includes(query) || r.transactionId?.toLowerCase().includes(query))
    : records;
  const doc = visible.find((r) => r.id === selectedDocId) || visible[0];

  const handleCopyHash = (text: string) => {
    navigator.clipboard.writeText(text);
    setHasCopiedHash(true);
    setTimeout(() => setHasCopiedHash(false), 2000);
  };

  // Generate downloadable Audit Trail Certificate
  const handleDownloadCertificate = async () => {
    if (!doc) return;

    const certText = `================================================================================
QUICKSIGN SIGNING CERTIFICATE
================================================================================
Certificate ID: ${doc.certificateId || 'Not signed yet'}
Transaction ID: ${doc.transactionId || 'Not signed yet'}
Document: ${doc.title}
Status: ${doc.status.toUpperCase()}
Created on: ${doc.createdAt}
Signed on: ${doc.signedAt || 'Not signed yet'}

SIGNERS:
${doc.signers
  .map(
    (s, idx) =>
      `[Signer ${idx + 1}] ${s.name} (${s.email}) · Role: ${s.role}
 Status: ${s.status === 'signed' ? 'SIGNED' : s.status === 'declined' ? 'DECLINED' : 'WAITING TO SIGN'}
 Signed on: ${s.signedAt || 'Not signed yet'}${s.viewLocation ? `
 Location when opening: ${formatLocation(s.viewLocation)}` : ''}${s.signLocation ? `
 Location when ${s.status === 'declined' ? 'declining' : 'signing'}: ${formatLocation(s.signLocation)}` : ''}`
  )
  .join('\n\n')}

ACTIVITY LOG:
${doc.auditTrail
  .map(
    (a) =>
      `• [${a.timestamp}] ${a.action}
  By: ${a.actor}
  IP address: ${a.ipAddress}${a.location ? `
  Location: ${formatLocation(a.location)}` : ''}
  Details: ${a.details}`
  )
  .join('\n\n')}

ABOUT THIS CERTIFICATE:
This certificate lists the signers of this document and every recorded action,
in the order they happened. It was generated by QuickSign.
Locations are shown only where a person chose to share them. Place names are
looked up from coordinates (data © OpenStreetMap contributors).
================================================================================`;

    try {
      const pdf = await textToPdfBlob(certText, { monospace: true, fontSize: 7.5 });
      downloadBlob(pdf, `QuickSign_Audit_Certificate_${safeFileName(doc.transactionId || doc.id)}.pdf`);
    } catch (err: any) {
      window.alert(err?.message || 'Could not generate the audit certificate.');
    }
  };

  return (
    <div className="flex-1 flex flex-col h-full bg-zinc-950 text-zinc-100 overflow-y-auto">
      {/* Top Header */}
      <div className="px-4 sm:px-8 py-5 sm:py-6 border-b border-zinc-800 bg-zinc-950">
        <div className="max-w-6xl mx-auto flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2">
              <ShieldCheck className="w-5 h-5 text-cyan-400" />
              <h1 className="text-xl font-bold tracking-tight text-white font-display">
                Audit Trail
              </h1>
            </div>
            <p className="text-xs text-zinc-400 mt-1">
              See who signed each document, when they signed, and every action taken on it.
            </p>
          </div>

          <div className="flex items-center gap-3">
            <button
              onClick={handleDownloadCertificate}
              disabled={!doc}
              className="flex items-center gap-1.5 px-4 py-2 bg-white text-zinc-950 hover:bg-zinc-200 font-semibold text-xs rounded transition-all cursor-pointer shadow-sm disabled:opacity-40"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Audit Certificate</span>
            </button>
          </div>
        </div>
      </div>

      {/* Main Content Area */}
      <div className="max-w-6xl w-full mx-auto p-4 sm:p-8 space-y-6">
        {/* Document Selection and Search */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          <div className="md:col-span-2 flex items-center gap-2 bg-zinc-950 border border-zinc-800 rounded-lg p-2.5">
            <label className="text-xs font-semibold text-zinc-400 pl-2 shrink-0">Document:</label>
            <select
              value={doc?.id || ''}
              onChange={(e) => {
                setSelectedDocId(e.target.value);
                if (documents.some((d) => d.id === e.target.value)) setActiveDocumentId(e.target.value);
              }}
              className="bg-transparent text-xs text-white focus:outline-none flex-1 truncate cursor-pointer font-medium"
            >
              {visible.map((d) => (
                <option key={d.id} value={d.id} className="bg-zinc-900 text-white">
                  {d.title} — Status: {d.status.toUpperCase()} {d.transactionId ? `(${d.transactionId})` : ''}
                </option>
              ))}
            </select>
          </div>

          <div className="relative">
            <Search className="w-3.5 h-3.5 absolute left-3 top-1/2 -translate-y-1/2 text-zinc-500" />
            <input
              type="text"
              value={searchTx}
              onChange={(e) => setSearchTx(e.target.value)}
              placeholder="Search by title or Transaction ID..."
              className="w-full pl-9 pr-3 py-2.5 bg-zinc-950 border border-zinc-800 rounded-lg text-xs text-white placeholder:text-zinc-600 focus:outline-none focus:border-cyan-500 transition-colors"
            />
          </div>
        </div>

        {!doc && (
          <div className="p-8 bg-zinc-950 border border-zinc-800 rounded-lg text-center text-xs text-zinc-400">
            {query ? 'No document matches that search.' : 'No documents yet. Send or sign a document and its history will appear here.'}
          </div>
        )}

        {doc && (
          <>
            {/* Primary Seal & Transaction ID Card */}
            <div className="p-4 sm:p-6 bg-zinc-950 border border-zinc-800 rounded-lg space-y-6">
              <div className="flex flex-col md:flex-row md:items-center justify-between pb-6 border-b border-zinc-800/80 gap-4">
                <div>
                  <span className="text-[10px] font-mono uppercase tracking-widest text-cyan-400">
                    DOCUMENT RECORD
                  </span>
                  <h2 className="text-lg font-bold text-white font-display mt-0.5">{doc.title}</h2>
                  <div className="flex items-center gap-2 text-xs text-zinc-400 mt-1">
                    <span>Created {new Date(doc.createdAt).toLocaleDateString()}</span>
                    <span aria-hidden="true">·</span>
                    <span>{doc.pages.length} Pages</span>
                    <span aria-hidden="true">·</span>
                    <span className="capitalize text-emerald-400 font-medium">{doc.status}</span>
                  </div>
                </div>

                <div className="flex flex-col md:items-end">
                  <span className="text-[10px] font-mono text-zinc-500 uppercase">
                    Transaction ID
                  </span>
                  <div className="text-base font-mono font-bold text-cyan-400">
                    {doc.transactionId || 'Not signed yet'}
                  </div>
                  <span className="text-[10px] font-mono text-zinc-500">
                    Certificate: {doc.certificateId || 'Not signed yet'}
                  </span>
                </div>
              </div>

              {/* Signature fingerprint */}
              <div className="p-4 bg-black/50 border border-zinc-800/80 rounded-md">
                <div className="flex items-center justify-between text-xs text-zinc-400 mb-1.5">
                  <span className="font-mono text-zinc-500 flex items-center gap-1.5">
                    <Lock className="w-3.5 h-3.5 text-cyan-400" />
                    <span>Signature fingerprint (SHA-256):</span>
                  </span>
                  <button
                    onClick={() => handleCopyHash(doc.sha256Hash || '')}
                    className="flex items-center gap-1 text-[11px] text-zinc-400 hover:text-white transition-colors cursor-pointer"
                  >
                    {hasCopiedHash ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                    <span>{hasCopiedHash ? 'Copied' : 'Copy Hash'}</span>
                  </button>
                </div>
                <div className="font-mono text-xs text-zinc-300 break-all select-all">
                  {doc.sha256Hash || 'Not signed yet'}
                </div>
              </div>

              {/* Signers Status Grid */}
              <div>
                <div className="text-[11px] font-medium uppercase tracking-wider text-zinc-400 mb-3">
                  Signers
                </div>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                  {doc.signers.map((signer, idx) => (
                    <div
                      key={idx}
                      className="p-3.5 bg-zinc-900/60 border border-zinc-800 rounded-md flex items-center justify-between"
                    >
                      <div className="flex items-center gap-3 min-w-0">
                        <div
                          className={`w-8 h-8 shrink-0 rounded-full flex items-center justify-center text-xs font-bold ${
                            signer.status === 'signed'
                              ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/40'
                              : 'bg-zinc-800 text-zinc-400'
                          }`}
                        >
                          <UserCheck className="w-4 h-4" />
                        </div>
                        <div>
                          <div className="text-xs font-semibold text-white">{signer.name}</div>
                          <div className="text-[11px] text-zinc-400">{signer.email}</div>
                          <div className="text-[10px] text-zinc-500 font-mono">{signer.role}</div>
                          {signer.signLocation && (
                            <LocationText
                              location={signer.signLocation}
                              label={signer.status === 'declined' ? 'Declined at:' : 'Signed at:'}
                              className="text-[10px] text-zinc-400 mt-1"
                            />
                          )}
                        </div>
                      </div>

                      <div className="text-right">
                        <span
                          className={`text-[10px] font-mono px-2 py-0.5 rounded uppercase font-semibold ${
                            signer.status === 'signed'
                              ? 'bg-emerald-500/20 text-emerald-300'
                              : signer.status === 'declined'
                              ? 'bg-rose-500/15 text-rose-300'
                              : 'bg-amber-500/10 text-amber-300'
                          }`}
                        >
                          {signer.status}
                        </span>
                        {signer.signedAt && (
                          <div className="text-[10px] font-mono text-zinc-500 mt-1">
                            {new Date(signer.signedAt).toLocaleDateString()}
                          </div>
                        )}
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            </div>

            {/* Chronological Audit Event Trail */}
            <div className="p-4 sm:p-6 bg-zinc-950 border border-zinc-800 rounded-lg space-y-4">
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <Clock className="w-4 h-4 text-cyan-400" />
                  <h3 className="text-sm font-semibold text-white font-display">
                    Activity Log
                  </h3>
                </div>
                <span className="text-xs font-mono text-zinc-500">
                  {doc.auditTrail.length} events
                </span>
              </div>

              <div className="space-y-3 relative before:absolute before:left-4 before:top-2 before:bottom-2 before:w-px before:bg-zinc-800">
                {doc.auditTrail.map((ev) => (
                  <div key={ev.id} className="relative pl-9 space-y-1">
                    <div className="absolute left-2.5 top-1.5 w-3 h-3 rounded-full bg-cyan-400 -translate-x-1/2 ring-4 ring-zinc-950"></div>
                    <div className="flex items-center justify-between text-xs">
                      <span className="font-semibold text-white font-display">{ev.action}</span>
                      <span className="font-mono text-[11px] text-zinc-500">
                        {new Date(ev.timestamp).toLocaleString()}
                      </span>
                    </div>
                    <p className="text-xs text-zinc-400">{ev.details}</p>
                    <div className="flex flex-wrap items-center gap-x-3 gap-y-1 text-[10px] font-mono text-zinc-500 pt-0.5">
                      <span>By: {ev.actor}</span>
                      <span aria-hidden="true">·</span>
                      <span>IP: {ev.ipAddress}</span>
                      {ev.location && (
                        <>
                          <span aria-hidden="true">·</span>
                          <LocationText location={ev.location} />
                        </>
                      )}
                    </div>
                  </div>
                ))}
              </div>
              {doc.auditTrail.some((ev) => ev.location?.shared && ev.location.place) && (
                <p className="text-[10px] text-zinc-500 pt-1">
                  Locations appear only where a person chose to share them. Place names: data ©{' '}
                  <a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noopener noreferrer" className="underline">
                    OpenStreetMap contributors
                  </a>
                  .
                </p>
              )}
            </div>
          </>
        )}
      </div>
    </div>
  );
};
